const catalog = [];
const seenSlugs = new Set();

// Function to generate slug
function toSlug(name) {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '');
}

// Populate base categories
for (const [category, meta] of Object.entries(masterCategories)) {
  for (const [name, desc] of meta.apps) {
    const slug = toSlug(name);
    if (!seenSlugs.has(slug)) {
      seenSlugs.add(slug);
      catalog.push({
        id: slug,
        name,
        category,
        icon: meta.icon,
        description: desc,
        authType: 'token_or_api_key',
        popular: ['github', 'gmail', 'slack', 'notion', 'figma', 'linear', 'discord', 'stripe', 'hubspot', 'jira', 'google_calendar', 'google_drive', 'spotify', 'openai'].includes(slug)
      });
    }
  }
}

